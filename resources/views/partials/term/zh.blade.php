                <h4 class="mt-20">Wongpanit Recycle Rayong Co., Ltd.</h4>
                <p class="blog_date">公告日期：2023 年 3 月 19 日</p>
                <p> Wongpanit Recycle Rayong Co., Ltd.（以下简称“本公司”）发布本个人信息政策，旨在让使用本公司产品和服务的客户，包括潜在客户、用户及访客（以下简称“您”或“客户”），了解本公司依据泰国佛历 2562 年（2019 年）《个人信息保护法》及相关法律法规收集、使用和披露个人信息的政策。本政策将说明本公司收集、使用或披露您的个人信息的方式、信息类型及目的，以及信息保存期限、向第三方披露个人信息、您的权利、个人信息的保密与安全，以及您与本公司联系的方式。</p>
                <p> <b>1. 个人信息的定义</b>
                    “个人信息”是指根据现行法律能够直接或间接识别某一个人的信息，不包括已故人士的个人信息。“敏感个人信息”是指涉及国籍、种族、政治观点、信仰、宗教或哲学信仰、犯罪记录、健康信息、残疾、工会信息、基因信息以及生物识别信息（如指纹和面部扫描）等，或根据个人信息保护委员会的公告和规定以类似方式影响信息主体的其他信息。
                </p>
                <br>
                <p> <b>2.1 个人信息的收集</b> </p>
                <p>本公司向您收集以下个人信息及其他信息：</p>

                <p> <b>1) 姓名</b>
                </p>
                <p> <b>2) 地址</b>
                </p>
                <p> <b>3) 电子邮箱</b></p>
                <p> <b>4) 电话号码</b></p>
                <p> <b>5) 网络社交联系方式（如 LINE ID、Facebook ID）
                </b></p>
                <p> <b>6) 您提供给本公司的其他个人信息
                </b>
                </p>
                <br>
                <p><b>2.2 个人信息的收集方式</b><br>
                    本公司通过多种渠道收集个人信息。本公司可直接在公司或通过网站 www.wpnrayong.com 或本公司其他网站接收您的信息，也可通过非直接来自您的其他来源获取，例如其他机构、安全服务提供商及网络社交媒体平台等。
                </p>

                <Br>
                    <p><b>2.3 个人信息的保存期限

                        </b><br>
                        在您作为本公司客户期间，本公司将根据既定目的收集并使用您的个人信息；在您不再是本公司客户后，本公司将根据个人信息收集目的或法律要求，在必要范围内继续保存和使用个人信息十年。

                    </p>

                <br>
                <p> <b>3. 收集个人信息的目的
                </b>
                </p>
                <p> 本公司将基于法律需要、您的同意或其他法律依据，为以下目的收集、使用和/或披露包括您的个人信息在内的信息：
                </p>

                <p>(1) 根据各项活动的规定和条件，使用并管理您的信息以开展本公司的营销活动。
                </p>
                <p>(2) 通过您提供的渠道向您提供有关产品、服务或营销活动的信息、建议和宣传，包括介绍本公司的商品和服务。
                </p>
                <p>(3) 开发本公司的商品和服务，包括促销及营销活动。</p>
                <p>(4) 与您沟通、回复并提供协助，以及提供售后服务。</p>
                <p>(5) 在为您提供服务前核实身份。</p>
                <p>(6) 研究和开发本公司的商品和服务。</p>
                <p>(7) 提供服务和/或联系、沟通、寄送邮包，例如就本公司商品和服务的满意度进行联络和询问，以及通知促销活动或特别折扣。
                </p>
                <p>(8) 履行合同。</p>
                <p>(9) 遵守法律和/或维护公共利益。</p>
                <p>(10) 防止或制止对个人生命、身体或健康的危害。</p>
                <br>
                <p>如您不向本公司提供个人信息，在某些情况下本公司可能无法为您提供服务。</p>
                <Br>
                    <p><b>4. 个人信息保护</b>
                    <br>
                    本公司将依据技术和管理措施妥善保存您的个人信息，以在个人信息处理过程中保持适当的安全性，防止未经授权或违法的个人信息侵害、丢失、访问、损坏、使用、变更、修改，或超出目的的使用或披露。
                    <br>
                    您可自由决定是否同意本公司收集、使用或披露您的个人信息。如该个人信息并非订立协议或使用服务所必需或相关，本公司不会将同意作为获取服务或订立协议的条件。此外，本公司要求其员工、人员、代表及信息接收方对您的个人信息保密，并在处理您的个人信息时遵守本公司规定的安全措施。
                    <br>
                    如个人信息主体未成年，即根据《民商法典》属于未成年人，您的同意须同时获得代您行使监护权之人的同意。如给予同意者为未满 10 周岁的未成年人，则须直接征得行使监护权之人的同意。
                    <br>
                    如个人信息主体为无行为能力人或限制行为能力人，视情况需要获得有权代表该无行为能力人或限制行为能力人行事的照护人或监护人的同意。本公司将采取措施确保该人信息准确、最新、完整且不具误导性。

                    </p>

                    <br>
                    <p><b>5. 个人信息的披露</b></p>
                    <p><b>5.1 个人信息接收方的类型</b> <br>
                        在业务经营中，本公司需要向为本公司提供服务的公司及本公司的贸易伙伴披露必要的个人信息，例如市场数据分析服务、产品运输服务、安全防护开发、应用程序开发、促销活动、通讯、邮政服务提供商，以及根据第 3 条所述信息使用目的进行的其他信息披露。
                    </p>

                    <p><b>5.2 向境外发送或转移个人信息</b><Br>
                        在某些情况下，本公司可能会将存储于本公司数据库中的信息转移至位于境外、由本公司贸易伙伴运营和管理的计算机上，该等伙伴具备符合泰国现行个人信息保护法律的充分保护标准。信息将在严格的安全措施下保存。
                    </p>

                    <p><b>6. 个人信息主体的权利</b><Br>
                        根据泰国现行个人信息保护法律的规定，您享有以下权利。</p>
                        <p>(1) 您可通过本公司在第 8 条提供的渠道撤回同意。本公司谨此告知，撤回同意可能导致您无法接收新闻、信息或优惠，包括本公司有关优惠和活动的通讯。
                        </p>
                        <p>(2) 您可要求访问、复制、修改或变更由本公司负责的您的个人信息，以确保其准确、最新、完整且不具误导性。
                        </p>
                        <p>
                            (3) 您可要求披露未经您同意而获取您个人信息的情况。
                        </p>
                        <p>
                            (4) 您有权要求本公司将您的个人信息发送或转移给其他个人信息控制者。
                        </p>
                        <p>
                            (5) 您可在法律规定的特定情况下，反对收集、使用或披露个人信息，或要求暂停使用个人信息。
                        </p>
                        <p>
                            (6) 您可根据法律规定，要求本公司删除、销毁个人信息或使其无法识别个人身份。
                        </p>
                        <p>
                            (7) 您可向有权的政府机构提出投诉。
                        </p>

                    <p><b>7. 个人信息政策的修订</b><Br>
                        本公司保留修订和完善本个人信息政策的权利，并将就上述修订和变更通知您。此外，如在本政策范围之外，本公司可能会通知您有关您个人信息的其他补充细节，例如收集您个人信息的目的。本个人信息政策的修订和变更或有关个人信息的其他细节，自本公司以其认为适当的方式通知您时立即生效；但如本公司依法需要征得您的同意，则相关修订和变更或与个人信息政策有关的任何其他信息，自本公司获得您的同意时生效。

                    </p>
